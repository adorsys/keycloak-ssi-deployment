#!/usr/bin/env bash
set -euo pipefail
IFS=$'\n\t'

# =============================================================================
# Keycloak SSI Deployment Wrapper
# =============================================================================
# Wraps the submodule CLI and adds infrastructure management (Terraform/Helm)
# =============================================================================

# Determine project root
determine_project_root() {
    local script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
    # Prefer running locally from the cloned repository
    if [[ -d "$script_dir/keycloak-oauth-sig" ]]; then
        echo "$script_dir"
        return
    fi
    # If installed, use XDG Base Directory
    local xdg_data_home="${XDG_DATA_HOME:-$HOME/.local/share}"
    local project_root="$xdg_data_home/keycloak-ssi-deployment"
    if [[ -d "$project_root/keycloak-oauth-sig" ]]; then
        echo "$project_root"
        return
    fi
    echo "Keycloak SSI project not found. Run from the project root or install with './keycloak-ssi.sh install'." >&2
    exit 1
}

PROJECT_ROOT="$(determine_project_root)"
TEST_DEPLOYMENT_DIR="$PROJECT_ROOT/keycloak-oauth-sig/oid4vci-deployment"
SUBMODULE_CLI="$TEST_DEPLOYMENT_DIR/keycloak-ssi.sh"
SSI_KEYCLOAK_DIR="$PROJECT_ROOT/deployment/keycloak"
SSI_CONFIG="$SSI_KEYCLOAK_DIR/config.override.yaml"
SSI_COMPOSE_OVERRIDE="$SSI_KEYCLOAK_DIR/docker-compose.override.yaml"

# Colors
if [ -t 1 ]; then
  CLI_GREEN="$(printf '\033[0;32m')"
  CLI_YELLOW="$(printf '\033[1;33m')"
  CLI_BLUE="$(printf '\033[1;34m')"
  CLI_RED="$(printf '\033[0;31m')"
  CLI_NC="$(printf '\033[0m')"
else
  CLI_GREEN=""; CLI_YELLOW=""; CLI_BLUE=""; CLI_RED=""; CLI_NC="";
fi

log() { echo -e "${CLI_BLUE}[WRAPPER]${CLI_NC} $1"; }
success() { echo -e "${CLI_GREEN}[SUCCESS]${CLI_NC} $1"; }
warn() { echo -e "${CLI_YELLOW}[WARN]${CLI_NC} $1"; }
error() { echo -e "${CLI_RED}[ERROR]${CLI_NC} $1"; exit 1; }

# =============================================================================
# Helper Functions
# =============================================================================

sync_providers() {
    local providers_dir="$PROJECT_ROOT/providers"
    local -a provider_jars=()
    local -a oid4vp_plugins=()
    local provider

    mapfile -d '' -t provider_jars < <(
        find "$providers_dir" -maxdepth 1 -type f -name '*.jar' -print0
    )
    mapfile -d '' -t oid4vp_plugins < <(
        find "$providers_dir" -maxdepth 1 -type f -name 'keycloak-oid4vp-plugin-*.jar' -print0
    )

    if [[ "${#provider_jars[@]}" -eq 0 ]]; then
        error "No Keycloak provider JARs found in $providers_dir."
    fi

    if [[ "${#oid4vp_plugins[@]}" -ne 1 ]]; then
        error "Expected exactly one keycloak-oid4vp-plugin-*.jar in $providers_dir; found ${#oid4vp_plugins[@]}."
    fi

    log "Using SSI-managed providers:"
    for provider in "${provider_jars[@]}"; do
        log "  - $(basename "$provider")"
    done
}

sync_config() {
    local local_override="$PROJECT_ROOT/config-override.yaml"
    local dest="$TEST_DEPLOYMENT_DIR/config.override.yaml"
    local generated_marker="# Generated by keycloak-ssi-deployment; edit the repository-root config-override.yaml instead."
    local generated_config

    if [[ ! -f "$SSI_CONFIG" ]]; then
        error "SSI Keycloak configuration not found: $SSI_CONFIG"
    fi

    if ! command -v yq >/dev/null 2>&1; then
        error "yq is required to prepare the Keycloak configuration."
    fi

    if [[ -f "$dest" ]] && ! grep -Fqx "$generated_marker" "$dest"; then
        error "An unmanaged $dest already exists. Move its environment-specific values to $local_override before running the wrapper."
    fi

    generated_config="$(mktemp "$dest.tmp.XXXXXX")"
    printf '%s\n' "$generated_marker" > "$generated_config"

    if [[ -f "$local_override" ]]; then
        log "Merging SSI defaults with local configuration from $local_override..."
        if ! yq eval-all '. as $item ireduce ({}; . * $item)' \
            "$SSI_CONFIG" "$local_override" >> "$generated_config"; then
            rm -f "$generated_config"
            error "Could not merge the Keycloak configuration."
        fi
    else
        log "Applying SSI-owned Keycloak configuration..."
        if ! yq eval '.' "$SSI_CONFIG" >> "$generated_config"; then
            rm -f "$generated_config"
            error "Could not prepare the Keycloak configuration."
        fi
    fi

    mv "$generated_config" "$dest"
}

sync_all() {
    sync_providers
    sync_config
}

check_submodule() {
    if [[ ! -f "$SUBMODULE_CLI" ]]; then
        error "Submodule CLI not found at $SUBMODULE_CLI.\nDid you run 'git submodule update --init --recursive'?"
    fi
}

